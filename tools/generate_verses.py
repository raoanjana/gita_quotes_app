#!/usr/bin/env python3
"""Rebuild Shared/VerseData.swift and preview/verses.json from Data/*.json.

Data/swarupananda.json defines which verses exist and their order, mapping
verse IDs ("2.47", "2.62–63") to Swarupananda's text.

Data/<translation>_short.json (optional) holds short word-for-word excerpts
used when a verse is too long for a small widget or the Lock Screen.

Explanations: Data/explanations.json (English). To add a language later, add
Data/explanations_<lang>.json and list it in EXPLANATION_FILES.

Run from the project folder:  python3 tools/generate_verses.py
"""
import json, os

TRANSLATIONS = ("swarupananda",)
EXPLANATION_FILES = {"en": "explanations"}

def load(name):
    with open(f"Data/{name}.json", encoding="utf-8") as f:
        return json.load(f)

def lit(s):
    assert '"#' not in s
    return '#"' + s.replace("\n", "\\#n") + '"#'

tr = {k: load(k) for k in TRANSLATIONS}
short = {k: load(f"{k}_short") for k in TRANSLATIONS if os.path.exists(f"Data/{k}_short.json")}
sanskrit = load("sanskrit")
explanations = {lang: load(f) for lang, f in EXPLANATION_FILES.items()}
ids = list(tr["swarupananda"].keys())

for name, table in [("Sanskrit", sanskrit)] + [(f"{l} explanation", e) for l, e in explanations.items()]:
    missing = [i for i in ids if i not in table]
    assert not missing, f"no {name} for {missing}"
for k in ("swarupananda",):
    missing = [i for i in ids if i not in tr[k]]
    assert not missing, f"{k} is missing {missing}"

out = ["// Generated by tools/generate_verses.py from Data/*.json. Do not edit by hand.", "",
       "enum VerseData {", "    static let verses: [Verse] = ["]
for i in ids:
    ch, v = i.split(".", 1)
    out.append(f'        Verse(chapter: {ch}, verse: "{v}",')
    out.append(f"              sanskrit: {lit(sanskrit[i])},")
    out.append("              explanations: [")
    for lang in EXPLANATION_FILES:
        out.append(f"                .{lang}: {lit(explanations[lang][i])},")
    out.append("              ],")
    out.append("              texts: [")
    for k in TRANSLATIONS:
        if i in tr[k]:
            out.append(f"                .{k}: {lit(tr[k][i])},")
    out.append("              ],")
    excerpts = [k for k in TRANSLATIONS if i in short.get(k, {})]
    if excerpts:
        out.append("              shortTexts: [")
        for k in excerpts:
            out.append(f"                .{k}: {lit(short[k][i])},")
        out.append("              ]),")
    else:
        out.append("              shortTexts: [:]),")
out += ["    ]", "}", ""]
with open("Shared/VerseData.swift", "w", encoding="utf-8") as f:
    f.write("\n".join(out))
with open("preview/verses.json", "w", encoding="utf-8") as f:
    json.dump({"ids": ids, "sanskrit": sanskrit, "explanations": explanations,
               "translations": tr, "short": short}, f, ensure_ascii=False)
# The all-verses page embeds the data so it opens straight from disk.
import re
page = open("preview/verses.html", encoding="utf-8").read()
blob = json.dumps({"ids": ids, "sanskrit": sanskrit, "explanations": explanations,
                   "translations": tr, "short": short}, ensure_ascii=False).replace("</", "<\\/")
page, n = re.subn(r'(<script id="data" type="application/json">).*?(</script>)',
                  lambda m: m.group(1) + blob + m.group(2), page, count=1, flags=re.S)
assert n == 1, "preview/verses.html has no data block"
with open("preview/verses.html", "w", encoding="utf-8") as f:
    f.write(page)
print(f"{len(ids)} verses written")
